#!/usr/bin/env python
"""Generate the Benchmarks task that makes a model read the engine source.

Stage A of `odd/tasks/llm-in-the-loop.md`. The economist task reasoned from a
~5 KB prose brief and proposed removing the tape's fertilizer buys as a
+$5,500..+$6,600 cash leak; measured, it is a -$210 wash, because the engine
quotes `BUY_PRODUCT` at the POST-buy inventory so that a buy/sell round trip nets
zero (`kaggriculture.py:599-601`). The brief had paraphrased the market and
dropped that rule. This task removes the paraphrase: the model gets the source.

Generated rather than hand-written because the engine is ~40 KB of Python and
embedding it by hand would rot the moment the engine version moves. Same shape as
`kaggle/arena/build_arena.py` and `kaggle/lab/build_notebook.py`.

Usage:
    .venv/bin/python kaggle/bench/build_engine_spec.py
    kaggle b t push kaggriculture-engine-spec -f kaggle/bench/kaggriculture-engine-spec.py --wait
    kaggle b t run kaggriculture-engine-spec -m claude-opus-4-5-20251101 --wait
    kaggle b t log kaggriculture-engine-spec -m claude-opus-4-5-20251101
"""

import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "kaggle" / "bench" / "kaggriculture-engine-spec.py"
ENGINE_GLOB = (
    ".venv/lib/python*/site-packages/kaggle_environments/envs/kaggriculture"
    "/kaggriculture.py"
)

BRIEF = '''You are auditing a simulation engine. Below is the COMPLETE source of the
environment for "Kaggriculture", a two-player farming game (30 days, 720 turns)
used in a Kaggle competition. Both players share one market and prices are a
deterministic function of market inventory.

Read the source and produce a RULE SHEET for someone who has to write a winning
plan. Do not summarise the game and do not praise the design; extract the
mechanics a plan must obey. Answer in under 900 words, as tables.

1. MARKET, VERB BY VERB. For every accepted market order verb (SELL, BUY_PRODUCT,
   BUY_SEED, BUY_ANIMAL, HIRE, BUY_LAND): the exact unit price the engine charges
   or pays, what that price is a function of, and how many units it may execute
   per call and per turn. State explicitly any pricing rule that makes a two-step
   buy-then-sell round trip net zero, and why the engine does it. Give the
   function name and the approximate line number for each.

2. SILENT FAILURES. List every input that is accepted and then silently ignored,
   truncated or no-opped instead of raising: order caps, unknown verbs, illegal
   targets, unmet preconditions (wrong structure under an animal, an item the
   worker is not carrying, a full shed, a locked tile). For each, the function and
   line, and what the caller observes when it happens.

3. PHYSICAL LIMITS. Tiles, structures, quadrants and their costs, shed capacity,
   per-crop and per-animal caps, growth and watering windows, exactly what turns a
   plant into a weed, and whether anything still has value when the season ends.

4. IMPOSSIBLE OR SELF-CANCELLING STRATEGIES. Name every plausible-sounding
   economic strategy that this source makes impossible or self-cancelling - for
   example a strategy that a reader who only knew the price table would believe
   works. Quote the function and line that kills each one.

5. THE THREE MOST DANGEROUS OMISSIONS. This game was previously summarised by hand
   in about one page and given to a model, which then proposed a strategy the
   engine cancels by design. Name the three rules most likely to be missing from
   such a hand-written summary, and state the wrong conclusion each omission
   would lead to.

THE ENGINE SOURCE
=================

'''


def find_engine(explicit: str | None) -> Path:
    if explicit:
        path = Path(explicit)
        if not path.is_file():
            raise SystemExit(f"engine not found: {path}")
        return path
    matches = sorted(REPO.glob(ENGINE_GLOB))
    if len(matches) != 1:
        raise SystemExit(
            f"expected exactly one engine source, found {len(matches)}: "
            f"{[str(m.relative_to(REPO)) for m in matches]}; pass --engine"
        )
    return matches[0]


def build(engine_path: Path) -> str:
    source = engine_path.read_text()
    # A docstring is the task description and must stay short; details go in
    # comments above the task that would otherwise fail validation.
    if "'''" in source:
        raise SystemExit("engine source contains a triple single quote; embed differently")
    body = source.rstrip("\n") + "\n"
    return (
        "# GENERATED by kaggle/bench/build_engine_spec.py - do not edit by hand.\n"
        "#\n"
        "# Stage A of odd/tasks/llm-in-the-loop.md: hand the model the complete\n"
        f"# engine source ({len(source):,} chars) instead of a hand-written summary.\n"
        "#\n"
        "#   kaggle b t push kaggriculture-engine-spec \\\n"
        "#       -f kaggle/bench/kaggriculture-engine-spec.py --wait\n"
        "#   kaggle b t run kaggriculture-engine-spec -m claude-opus-4-5-20251101 --wait\n"
        "#   kaggle b t log kaggriculture-engine-spec -m claude-opus-4-5-20251101\n"
        "\n"
        "# %%\n"
        '"""Extract the engine\'s authoritative rule sheet from its own source."""\n'
        "\n"
        "import kaggle_benchmarks as kbench  # type: ignore[import-not-found]\n"
        "\n"
        "# %%\n"
        "BRIEF = " + repr(BRIEF) + "\n"
        "\n"
        "ENGINE_SOURCE = r'''\n" + body + "'''\n"
        "\n"
        "\n"
        "# %%\n"
        '@kbench.task(name="kaggriculture-engine-spec")\n'
        "def kaggriculture_engine_spec(llm):\n"
        '    """Read the engine source and write its authoritative rule sheet."""\n'
        "    response = llm.prompt(BRIEF + ENGINE_SOURCE)\n"
        '    print("=" * 72)\n'
        '    print("ENGINE RULE SHEET")\n'
        '    print("=" * 72)\n'
        "    print(response)\n"
        '    print("=" * 72)\n'
        "\n"
        "\n"
        "# %%\n"
        "kaggriculture_engine_spec.run(kbench.llm)  # type: ignore[attr-defined]\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--engine", help="path to kaggriculture.py (default: the venv copy)")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args()

    engine_path = find_engine(args.engine)
    generated = build(engine_path)

    if args.check:
        current = OUT.read_text() if OUT.is_file() else ""
        if current != generated:
            raise SystemExit(f"{OUT.relative_to(REPO)} is stale; regenerate it")
        print(f"{OUT.relative_to(REPO)} is up to date")
        return

    OUT.write_text(generated)
    print(f"engine:    {engine_path.relative_to(REPO)}")
    print(f"generated: {OUT.relative_to(REPO)}  ({len(generated):,} chars)")


if __name__ == "__main__":
    main()
